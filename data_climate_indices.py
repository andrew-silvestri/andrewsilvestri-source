def monthly(series):
    """Flatten a year-keyed block into (year, month, value) triples."""
    out = []
    for year, vals in series:
        for i, v in enumerate(vals):
            out.append((year, i + 1, v))
    return out


def annual(series):
    """Calendar-year means. Partial years are averaged over what exists."""
    return [(y, sum(v) / len(v)) for y, v in series if v]


def djf(series):
    """
    Winter means, labelled by the January year: December of the previous year
    with January and February of this one. This is the season the NAO is
    normally quoted for, and the one the energy literature uses.
    """
    by = {y: v for y, v in series}
    out = []
    for y in sorted(by):
        if y - 1 not in by or len(by[y - 1]) < 12 or len(by[y]) < 2:
            continue
        out.append((y, (by[y - 1][11] + by[y][0] + by[y][1]) / 3.0))
    return out


